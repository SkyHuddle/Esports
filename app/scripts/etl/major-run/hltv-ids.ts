export function resolveHltvId(gamertag: string): number | undefined {
  const normalized = gamertag.trim().toLowerCase().replace(/[^a-z0-9_-]/g, '');
  if (HLTV_ID_BY_TAG[normalized]) return HLTV_ID_BY_TAG[normalized];

  for (const [tag, id] of Object.entries(HLTV_ID_BY_TAG)) {
    if (tag.toLowerCase() === normalized) return id;
  }
  return undefined;
}
